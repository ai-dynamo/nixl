/*
 * The scenario table. Twenty status-returning southbound calls against the
 * status codes a plugin may return would be several hundred single-fault runs,
 * nearly all of which exercise the same few lines of agent mapping code, so the
 * set below is cut down to the cases that can differ: every site is covered at
 * least once, with a second status wherever the agent's mapping is not uniform
 * (a site that collapses to NIXL_ERR_BACKEND gets both NIXL_ERR_BACKEND and
 * something else, so the collapse is visible) and extra entries where the agent
 * branches on the value itself, such as NIXL_ERR_REMOTE_DISCONNECT,
 * NIXL_ERR_NOT_SUPPORTED, and NIXL_IN_PROG.
 *
 * Grouped by the northbound call under test: creation, registration, metadata,
 * connection, transfer, memory views, notifications, optional APIs, cleanup,
 * and agent-side rejections that need no injection at all.
 */

